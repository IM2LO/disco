const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const assert = require('node:assert/strict');
(async () => {
 const browser = await chromium.launch({channel:'msedge',headless:true});
 const page = await browser.newPage({viewport:{width:390,height:844}});
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.DISCO_URL || 'http://localhost:8765');
 assert.equal(await page.title(),'Disco1');
 assert.equal(await page.locator('.view').count(),1);
 assert.ok(await page.locator('.planning-row').count()>0);
 await page.evaluate(()=>localStorage.setItem('contract-shifts-v1','original-sentinel'));
 await page.locator('[data-edit-day="2026-10-27"]').click();
 await page.locator('#dayWorked').check({force:true});
 await page.locator('#shiftStart').fill('07:50');
 await page.locator('#shiftEnd').fill('15:50');
 await page.locator('.provisional-toggle').click();
 await page.locator('.attraction-field label').first().click();
 await page.locator('#shiftNote').fill('Vérification Disco1');
 await page.locator('#dayForm button[type="submit"]').click();
 assert.equal(await page.locator('#daySheet').isVisible(),false);
 await page.reload();
 await page.locator('[data-planning-filter="provisional"]').click();
 assert.equal(await page.locator('.planning-row').count(),1);
 assert.ok((await page.locator('.planning-row').innerText()).includes('07:50–15:50'));
 assert.equal(await page.evaluate(()=>localStorage.getItem('contract-shifts-v1')),'original-sentinel');
 await page.locator('#jumpTodayPlanning').click();
 assert.ok(await page.locator('.planning-row').count()>1);
 await page.locator('#openSettings').click();
 const downloadPromise=page.waitForEvent('download');
 await page.locator('#exportShifts').click();
 const download=await downloadPromise;
 assert.ok(download.suggestedFilename().startsWith('disco1-shifts-'));
 page.once('dialog',d=>d.accept());
 await page.locator('#shiftBackupFile').setInputFiles({name:'planning.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({contract:{start:'2026-10-01',end:'2026-10-31'},shifts:{'2026-10-28':{worked:true,start:'10:00',end:'14:00',attraction:'STT'}}}))});
 await page.waitForTimeout(100);
 assert.equal(await page.locator('.planning-row').count(),31);
 await page.keyboard.press('Escape');
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.screenshot({path:process.env.TEMP+'/disco-mobile.png'});
 await page.setViewportSize({width:1280,height:900});
 await page.screenshot({path:process.env.TEMP+'/disco-desktop.png'});
 await browser.close();
 assert.deepEqual(errors,[]);
 console.log('Planning: mobile rendering, edit, pauses, persistence, filters, export and independent storage OK');
})().catch(e=>{console.error(e);process.exit(1)});
